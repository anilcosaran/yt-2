import crypto from 'node:crypto'
import fs from 'node:fs'

const translationFiles = [
  'scripts/tool-copy-translations-1.json',
  'scripts/tool-copy-translations-2.json',
  'scripts/tools-workspace-raw-translations.json',
]
const translations = Object.assign({}, ...translationFiles.map((file) => JSON.parse(fs.readFileSync(file, 'utf8'))))
const enPath = 'messages/en.json'
const trPath = 'messages/tr.json'
const en = JSON.parse(fs.readFileSync(enPath, 'utf8'))
const tr = JSON.parse(fs.readFileSync(trPath, 'utf8'))
const rawToKey = new Map(Object.entries(en.Auto ?? {}).map(([key, value]) => [value, key]))

for (const [raw, value] of Object.entries(translations)) {
  const hash = crypto.createHash('sha1').update(raw).digest('hex').slice(0, 8)
  const slug = raw
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 48) || 'message'
  const key = `tool_${slug}_${hash}`
  en.Auto[key] = value.en
  tr.Auto[key] = value.tr
  rawToKey.set(raw, key)
}

fs.writeFileSync(enPath, `${JSON.stringify(en, null, 2)}\n`, 'utf8')
fs.writeFileSync(trPath, `${JSON.stringify(tr, null, 2)}\n`, 'utf8')

const entries = [...rawToKey.entries()].sort(([left], [right]) => left.localeCompare(right))
const generated = `// Generated by scripts/build-tool-copy-map.mjs.\nexport const TOOL_COPY_KEYS: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const\n`
fs.writeFileSync('lib/i18n/tool-copy.generated.ts', generated, 'utf8')
