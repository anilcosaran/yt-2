// Keeps i18n/message-fragments.generated.ts (the static imports of messages/<locale>/*.json that
// Next.js and Vitest bundle) in sync with the fragment files.
//
//   node scripts/message-fragments.mjs --write   regenerate (also after a merge conflict in the index)
//   node scripts/message-fragments.mjs --check   fail when the index is stale
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

import { fragmentNamespace } from '../i18n/merge-message-fragments.mjs'

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const MESSAGES_DIR = path.join(projectRoot, 'messages')
export const FRAGMENT_INDEX = path.join(projectRoot, 'i18n', 'message-fragments.generated.ts')

/**
 * Fragment files of every locale that has a `messages/<locale>.json`, sorted by locale then file name.
 * Throws on a file whose name is not `<Namespace>[.<feature>].json`.
 */
export function listMessageFragments(messagesDir = MESSAGES_DIR) {
  const locales = fs.readdirSync(messagesDir)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .sort()
  const fragments = []
  for (const locale of locales) {
    const directory = path.join(messagesDir, locale)
    if (!fs.existsSync(directory)) continue
    for (const name of fs.readdirSync(directory).sort()) {
      const namespace = fragmentNamespace(name)
      if (!namespace || !fs.statSync(path.join(directory, name)).isFile()) {
        throw new Error(`messages/${locale}/${name}: fragment files are named <Namespace>[.<feature>].json`)
      }
      fragments.push({ locale, namespace, file: `${locale}/${name}`, path: path.join(directory, name) })
    }
  }
  return { locales, fragments }
}

export function renderFragmentIndex({ locales, fragments }) {
  const identifier = (fragment) => `${fragment.locale}_${fragment.file.slice(fragment.locale.length + 1, -'.json'.length).replace(/[^A-Za-z0-9]/g, '_')}`
  const lines = [
    '// Generated by scripts/message-fragments.mjs from messages/<locale>/*.json; do not edit.',
    '// Run `npm run i18n:fragments` after adding, renaming or removing a fragment file.',
    "import type { AbstractIntlMessages } from 'next-intl'",
    '',
  ]
  for (const fragment of fragments) lines.push(`import ${identifier(fragment)} from '@/messages/${fragment.file}'`)
  if (fragments.length > 0) lines.push('')
  lines.push(
    'export interface MessageFragment {',
    '  readonly file: string',
    '  readonly namespace: string',
    '  readonly messages: AbstractIntlMessages',
    '}',
    '',
    'export const messageFragments: Readonly<Record<string, readonly MessageFragment[]>> = {',
  )
  for (const locale of locales) {
    const own = fragments.filter((fragment) => fragment.locale === locale)
    if (own.length === 0) {
      lines.push(`  ${locale}: [],`)
      continue
    }
    lines.push(`  ${locale}: [`)
    for (const fragment of own) {
      lines.push(`    { file: '${fragment.file}', namespace: '${fragment.namespace}', messages: ${identifier(fragment)} },`)
    }
    lines.push('  ],')
  }
  lines.push('}', '')
  return lines.join('\n')
}

function main(argv) {
  const expected = renderFragmentIndex(listMessageFragments())
  const current = fs.existsSync(FRAGMENT_INDEX) ? fs.readFileSync(FRAGMENT_INDEX, 'utf8').replace(/\r\n/g, '\n') : null
  if (argv.includes('--write')) {
    if (current !== expected) fs.writeFileSync(FRAGMENT_INDEX, expected)
    console.log(`Message fragment index ${current === expected ? 'unchanged' : 'written'}: ${path.relative(projectRoot, FRAGMENT_INDEX)}`)
    return
  }
  if (current !== expected) {
    console.error('i18n/message-fragments.generated.ts is stale. Run `npm run i18n:fragments` and commit the result.')
    process.exitCode = 1
    return
  }
  console.log('Message fragment index up to date.')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2))
}
